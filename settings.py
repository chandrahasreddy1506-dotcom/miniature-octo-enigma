def env_bool(name, default=False):
    value = os.getenv(name)
    if value is None:
        return default

    return value.strip().lower() in {"1", "true", "yes", "on"}


def env_list(name, default=""):
    value = os.getenv(name, default)
    return [item.strip() for item in value.split(",") if item.strip()]


def database_config_from_env(default_sqlite_path):
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": default_sqlite_path,
        }

    parsed = urlparse(database_url)
    scheme = parsed.scheme.lower()

    if scheme in {"postgres", "postgresql", "pgsql"}:
        return {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": parsed.path.lstrip("/"),
            "USER": parsed.username or "",
            "PASSWORD": parsed.password or "",
            "HOST": parsed.hostname or "",
            "PORT": str(parsed.port or ""),
            "CONN_MAX_AGE": int(os.getenv("DB_CONN_MAX_AGE", "60")),
            "OPTIONS": {
                "sslmode": os.getenv("DB_SSLMODE", "require"),
            },
        }

    if scheme == "sqlite":
        sqlite_path = parsed.path.lstrip("/")
        if os.name == "nt" and sqlite_path.startswith(":"):
            sqlite_path = sqlite_path.lstrip(":")

        return {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": sqlite_path or default_sqlite_path,
        }

    raise ValueError("Unsupported DATABASE_URL scheme. Use postgres:// or sqlite://")


